        0x00, 0x00, 0x80, 0x03, 0x00, 0x00, 0x80, 0x03, 0x00, 0x00, 0x80, 0x03,
        0x80, 0x01, 0x00, 0x00, 0x80, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ]

    private static let bytesPerRow = (width + 7) / 8

    private static let litPixels: [(col: Int, row: Int)] = {
        var points: [(Int, Int)] = []
        for row in 0..<height {
            for col in 0..<width {
                let byte = bits[row * bytesPerRow + col / 8]
                if (byte >> (col % 8)) & 1 == 1 {
                    points.append((col, row))
                }
            }
        }
        return points
    }()

    var body: some View {
        Canvas { context, size in
            let cell = min(size.width / CGFloat(Self.width), size.height / CGFloat(Self.height))
            let originX = (size.width - cell * CGFloat(Self.width)) / 2
            let originY = (size.height - cell * CGFloat(Self.height)) / 2
            for point in Self.litPixels {
                let rect = CGRect(
                    x: originX + CGFloat(point.col) * cell,
                    y: originY + CGFloat(point.row) * cell,
                    width: cell,
                    height: cell)
                context.fill(Path(rect), with: .color(.primary))
            }
        }
        .aspectRatio(CGFloat(Self.width) / CGFloat(Self.height), contentMode: .fit)
        .accessibilityLabel("Original xsky icon glyph")
    }
}

