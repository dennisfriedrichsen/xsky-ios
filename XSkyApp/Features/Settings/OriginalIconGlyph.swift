import SwiftUI

/// Faithful reproduction of `xsky_icon`, the 28x48 XBM bitmap icon shipped
/// with the original X11 xsky, drawn pixel-for-pixel from its bit data.
struct OriginalIconGlyph: View {
    private static let width = 28
    private static let height = 48

    private static let bits: [UInt8] = [
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x1c, 0x00, 0x00, 0x00, 0x1c, 0x00, 0x00, 0x00, 0x1c, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x00, 0x00, 0x00, 0x18, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
