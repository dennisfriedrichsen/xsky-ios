#!/usr/bin/env python3
"""Generate Swift data tables from legacy xsky C headers.

Usage: tools/golden/gen_tables.py [path-to-legacy-xsky-checkout]

Reads constell.h, con-bounds.h, greek.h, bsc5_greek.h, and messier.h from
the read-only legacy checkout and emits Swift source files into
Packages/XSkyCore/Sources/XSkyCore/Generated/. Re-run only when the legacy
tables change; the outputs are checked in.
"""

import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent
LEGACY = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO_ROOT.parent / "xsky"
OUT_DIR = REPO_ROOT / "Packages/XSkyCore/Sources/XSkyCore/Generated"

HEADER = """// Generated by tools/golden/gen_tables.py from the legacy xsky
// C headers (copyright 1992-6 Terry R. Friedrichsen). Do not edit by hand.

"""


def read_string_array(text, name):
    m = re.search(
        r"char \*%s\[[^\]]*\] = \{(.*?)\};" % re.escape(name), text, re.S
    )
    return re.findall(r'"([^"]*)"', m.group(1))


def gen_constellations():
    text = (LEGACY / "constell.h").read_text()
    abbrev = read_string_array(text, "constellations_abbrev")
    latin = read_string_array(text, "constellations_latin")
    names = read_string_array(text, "constellations")
    assert len(abbrev) == len(latin) == len(names) == 89
    lines = [HEADER]
    lines.append("/// The 88 IAU constellations plus Serpens Cauda, indexed as in the\n")
    lines.append("/// legacy constell.h (alphabetical by abbreviation).\n")
    lines.append("public struct ConstellationTable: Sendable {\n")
    lines.append("    public struct Entry: Sendable {\n")
    lines.append("        public let abbreviation: String\n")
    lines.append("        public let genitive: String\n")
    lines.append("        public let name: String\n")
    lines.append("    }\n\n")
    lines.append("    public static let entries: [Entry] = [\n")
    for a, l, n in zip(abbrev, latin, names):
        lines.append(
            '        Entry(abbreviation: "%s", genitive: "%s", name: "%s"),\n'
            % (a, l, n)
        )
    lines.append("    ]\n")
    lines.append("}\n")
    (OUT_DIR / "ConstellationTable.swift").write_text("".join(lines))


def gen_roman_bounds():
    text = (LEGACY / "con-bounds.h").read_text()
    rows = re.findall(
        r"\{\s*([\d.]+),\s*([\d.]+),\s*(-?[\d.]+),\s*(\d+)\s*\}", text
    )
    lines = [HEADER]
    lines.append("/// Dr. Nancy G. Roman's constellation boundary table\n")
    lines.append("/// (1987, PASP, 99, 695): east-west south-boundary segments in\n")
    lines.append("/// B1875 decimal hours/degrees, with constellation indexes into\n")
    lines.append("/// ConstellationTable.entries.\n")
    lines.append("struct RomanBoundarySegment: Sendable {\n")
    lines.append("    let raLower: Double\n")
    lines.append("    let raUpper: Double\n")
    lines.append("    let declination: Double\n")
    lines.append("    let constellationIndex: Int\n")
    lines.append("}\n\n")
    lines.append("let romanBoundaryTable: [RomanBoundarySegment] = [\n")
    for ral, rau, decl, idx in rows:
        lines.append(
            "    RomanBoundarySegment(raLower: %s, raUpper: %s, "
            "declination: %s, constellationIndex: %s),\n" % (ral, rau, decl, idx)
        )
    lines.append("]\n")
    (OUT_DIR / "RomanBoundaryTable.swift").write_text("".join(lines))
    print("roman rows:", len(rows))


def gen_greek():
    full = read_string_array((LEGACY / "greek.h").read_text(), "greek")
    assert len(full) == 24
    lines = [HEADER]
    lines.append("/// Greek letter names in Bayer index order (legacy greek.h).\n")
    lines.append("public enum GreekLetters {\n")
    lines.append("    public static let names: [String] = [\n")
    for g in full:
        lines.append('        "%s",\n' % g)
    lines.append("    ]\n\n")
    lines.append("    /// Unicode lowercase Greek letters in the same order.\n")
    lines.append("    public static let symbols: [String] = [\n")
    symbols = [
        "α", "β", "γ", "δ", "ε", "ζ", "η", "θ", "ι", "κ", "λ", "μ",
        "ν", "ξ", "ο", "π", "ρ", "σ", "τ", "υ", "φ", "χ", "ψ", "ω",
    ]
    for s in symbols:
        lines.append('        "%s",\n' % s)
    lines.append("    ]\n")
    lines.append("}\n")
    (OUT_DIR / "GreekLetters.swift").write_text("".join(lines))


def gen_messier():
    text = (LEGACY / "messier.h").read_text()
    m = re.search(r"int messier_trans\[[^\]]*\] = \{(.*?)\};", text, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    nums = [int(x) for x in re.findall(r"(\d+)\s*,?", body)]
    assert len(nums) == 109, len(nums)
    lines = [HEADER]
    lines.append("/// Messier number (index + 1) to NGC number translation\n")
    lines.append("/// (legacy messier.h). Zero means no NGC counterpart.\n")
    lines.append("public enum MessierTable {\n")
    lines.append("    public static let ngcNumbers: [Int] = [\n")
    for i in range(0, len(nums), 10):
        lines.append(
            "        " + ", ".join(str(n) for n in nums[i : i + 10]) + ",\n"
        )
    lines.append("    ]\n")
    lines.append("}\n")
    (OUT_DIR / "MessierTable.swift").write_text("".join(lines))


OUT_DIR.mkdir(parents=True, exist_ok=True)
gen_constellations()
gen_roman_bounds()
gen_greek()
gen_messier()
print("wrote Swift tables to", OUT_DIR)
